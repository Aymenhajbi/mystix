-- Atelys Device Hub (ADR-0019, lot D): terminals that check in, selection profiles, scan diagnostics.
-- No secret and no hardware identifier is stored: a terminal is known by the installation id Atelys generated.

CREATE TABLE mobile_device (
    id                  UUID         PRIMARY KEY,
    company_id          UUID         NOT NULL REFERENCES company (id),
    installation_id     VARCHAR(64)  NOT NULL,
    label               VARCHAR(80),
    manufacturer        VARCHAR(80)  NOT NULL,
    brand               VARCHAR(80),
    model               VARCHAR(80)  NOT NULL,
    product             VARCHAR(80),
    android_release     VARCHAR(20),
    sdk_int             INTEGER      NOT NULL,
    build_id            VARCHAR(100),
    app_version         VARCHAR(40),
    capabilities        JSONB        NOT NULL DEFAULT '[]',
    resolution_state    VARCHAR(30),
    recommended_adapter VARCHAR(60),
    resolution_reasons  JSONB        NOT NULL DEFAULT '[]',
    active_adapter      VARCHAR(60),
    validated_at        TIMESTAMPTZ,
    preferred_adapter   VARCHAR(60),
    preferred_by        VARCHAR(254),
    preferred_at        TIMESTAMPTZ,
    reset_requested_at  TIMESTAMPTZ,
    test_requested_at   TIMESTAMPTZ,
    last_error_code     VARCHAR(40),
    last_error_at       TIMESTAMPTZ,
    last_seen_at        TIMESTAMPTZ  NOT NULL,
    last_seen_by        VARCHAR(254),
    created_at          TIMESTAMPTZ  NOT NULL,
    updated_at          TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_mobile_device_installation UNIQUE (company_id, installation_id),
    CONSTRAINT ck_mobile_device_resolution CHECK (resolution_state IS NULL OR resolution_state IN
        ('AUTO_SELECTED', 'USER_SELECTION_REQUIRED', 'CONFIGURATION_REQUIRED', 'DEVICE_UNSUPPORTED',
         'SCANNER_UNAVAILABLE', 'DIAGNOSTIC_REQUIRED')),
    CONSTRAINT ck_mobile_device_validated CHECK ((active_adapter IS NULL) = (validated_at IS NULL))
);
CREATE INDEX ix_mobile_device_company ON mobile_device (company_id, last_seen_at DESC);

CREATE TABLE mobile_device_profile (
    id                  UUID         PRIMARY KEY,
    company_id          UUID         NOT NULL REFERENCES company (id),
    name                VARCHAR(80)  NOT NULL,
    version             INTEGER      NOT NULL,
    scope               VARCHAR(20)  NOT NULL,
    manufacturer        VARCHAR(80)  NOT NULL,
    models              JSONB        NOT NULL DEFAULT '[]',
    installation_id     VARCHAR(64),
    min_sdk             INTEGER,
    max_sdk             INTEGER,
    recommended_adapter VARCHAR(60)  NOT NULL,
    prerequisites       TEXT,
    confidence          VARCHAR(10)  NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    test_procedure      TEXT,
    created_at          TIMESTAMPTZ  NOT NULL,
    updated_at          TIMESTAMPTZ  NOT NULL,
    updated_by          VARCHAR(254),
    CONSTRAINT ck_mobile_profile_scope CHECK (scope IN ('INSTALLATION', 'MODEL', 'MANUFACTURER')),
    CONSTRAINT ck_mobile_profile_status CHECK (status IN ('VALIDATED', 'EXPERIMENTAL', 'RETIRED')),
    CONSTRAINT ck_mobile_profile_confidence CHECK (confidence IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_mobile_profile_installation CHECK ((scope = 'INSTALLATION') = (installation_id IS NOT NULL)),
    CONSTRAINT ck_mobile_profile_sdk CHECK (min_sdk IS NULL OR max_sdk IS NULL OR min_sdk <= max_sdk),
    CONSTRAINT ck_mobile_profile_version CHECK (version >= 1)
);
CREATE INDEX ix_mobile_profile_company ON mobile_device_profile (company_id, status);

-- id is generated by the terminal: sending the same diagnostic twice stores it once.
CREATE TABLE mobile_device_diagnostic (
    id           UUID         PRIMARY KEY,
    company_id   UUID         NOT NULL REFERENCES company (id),
    device_id    UUID         NOT NULL REFERENCES mobile_device (id),
    adapter_id   VARCHAR(60)  NOT NULL,
    outcome      VARCHAR(20)  NOT NULL,
    simulated    BOOLEAN      NOT NULL,
    symbology    VARCHAR(40),
    data_length  INTEGER,
    error_code   VARCHAR(40),
    started_at   TIMESTAMPTZ  NOT NULL,
    finished_at  TIMESTAMPTZ  NOT NULL,
    received_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_mobile_diagnostic_outcome CHECK (outcome IN
        ('PASSED', 'MISMATCH', 'TIMEOUT', 'OPEN_FAILED', 'ADAPTER_ERROR', 'CANCELLED')),
    CONSTRAINT ck_mobile_diagnostic_time CHECK (finished_at >= started_at)
);
CREATE INDEX ix_mobile_diagnostic_device ON mobile_device_diagnostic (device_id, finished_at DESC);
